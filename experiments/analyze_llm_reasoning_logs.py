"""
analyze_llm_reasoning_logs.py

Analyzes all supervisory logs generated by the Tri-State Meta-LLM Supervisor.
Computes:
1. Intent-to-Action Alignment Score (%)
2. State Transition Distribution per scenario
3. Window-to-Window Causal Impact (Delta Backlog, Delta Holding Cost)
4. Formatted Case Study Vignettes for publications and reports.
"""

import os
import sys
import glob
import json
import re
import numpy as np
from typing import List, Dict, Any

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

def classify_intent_from_text(reasoning_text: str) -> str:
    """Classifies natural language reasoning into the intended strategic mode."""
    text = reasoning_text.lower()
    
    # Check for backlog / recovery intent
    backlog_keywords = ["backlog", "stockout", "deficit", "recovery", "catch up", "expedite", "clear backlog", "unfulfilled"]
    # Check for shock absorber / bullwhip dampening intent
    shock_keywords = ["shock", "damp", "bullwhip", "overflow", "excess inventory", "cool down", "stabilize upstream", "throttle"]
    # Check for cruiser / steady state intent
    cruiser_keywords = ["cruiser", "steady", "nominal", "stable", "normal", "maintain balance", "optimal baseline"]
    
    score_backlog = sum(1 for kw in backlog_keywords if kw in text)
    score_shock = sum(1 for kw in shock_keywords if kw in text)
    score_cruiser = sum(1 for kw in cruiser_keywords if kw in text)
    
    if score_backlog > score_shock and score_backlog > score_cruiser:
        return "BACKLOG_CLEARER"
    elif score_shock > score_backlog and score_shock > score_cruiser:
        return "SHOCK_ABSORBER"
    elif score_cruiser > 0:
        return "CRUISER"
    else:
        # Fallback to text matching
        if "0.65" in text or "backlog" in text:
            return "BACKLOG_CLEARER"
        elif "0.10" in text or "0.1" in text or "shock" in text:
            return "SHOCK_ABSORBER"
        else:
            return "CRUISER"

def analyze_log_directory(log_dir: str, scenario_name: str) -> Dict[str, Any]:
    """Parses all .jsonl trace logs in a given directory."""
    files = sorted(glob.glob(os.path.join(log_dir, "*.jsonl")))
    if not files:
        # Check subdirectories
        files = sorted(glob.glob(os.path.join(log_dir, "**", "*.jsonl"), recursive=True))
        
    if not files:
        print(f"[WARNING] No .jsonl log files found in {log_dir}")
        return {}

    total_decisions = 0
    aligned_decisions = 0
    mode_counts = {"CRUISER": 0, "SHOCK_ABSORBER": 0, "BACKLOG_CLEARER": 0, "HYBRID": 0}
    
    vignettes = []
    causal_deltas = []
    
    for fpath in files:
        with open(fpath, "r", encoding="utf-8") as f:
            lines = [json.loads(line) for line in f if line.strip()]
            
        for i, entry in enumerate(lines):
            total_decisions += 1
            alphas = entry.get("assigned_alphas") or entry.get("alphas", [0.375, 0.375, 0.375, 0.375])
            diagnosis = entry.get("diagnosis", "")
            rationale = entry.get("rationale", "")
            reasoning = f"{diagnosis} {rationale}".strip()
            target_mode = entry.get("target_mode", "")
            
            # Identify action mode
            if all(np.isclose(a, 0.375) for a in alphas):
                action_mode = "CRUISER"
            elif all(np.isclose(a, 0.10) for a in alphas):
                action_mode = "SHOCK_ABSORBER"
            elif all(np.isclose(a, 0.65) for a in alphas) or any(np.isclose(a, 0.65) for a in alphas):
                action_mode = "BACKLOG_CLEARER"
            else:
                action_mode = "HYBRID"
                
            mode_counts[action_mode] = mode_counts.get(action_mode, 0) + 1
            
            # Check intent
            inferred_intent = classify_intent_from_text(reasoning)
            is_aligned = (
                (inferred_intent == action_mode) or
                (target_mode and target_mode in action_mode) or
                ("MULTI_TIER_RECOVERY" in target_mode and action_mode == "BACKLOG_CLEARER") or
                (inferred_intent == "BACKLOG_CLEARER" and any(np.isclose(a, 0.65) for a in alphas))
            )
            if is_aligned:
                aligned_decisions += 1
                
            # Measure causal delta if next window exists
            if i + 1 < len(lines):
                next_entry = lines[i + 1]
                curr_perf = entry.get("perf_summary", {})
                next_perf = next_entry.get("perf_summary", {})
                
                curr_cost = curr_perf.get("window_cost", 0.0)
                next_cost = next_perf.get("window_cost", 0.0)
                curr_sl = curr_perf.get("service_level", 0.0)
                next_sl = next_perf.get("service_level", 0.0)
                
                causal_deltas.append({
                    "action_mode": action_mode,
                    "delta_cost": next_cost - curr_cost,
                    "delta_sl": next_sl - curr_sl
                })
                
            # Collect representative vignettes
            if len(vignettes) < 5:
                if (action_mode != "CRUISER") or (i == 0 and len(vignettes) == 0):
                    vignettes.append({
                        "trace_id": os.path.basename(fpath),
                        "timestep": entry.get("timestep", (i + 1) * 20),
                        "action_mode": target_mode or action_mode,
                        "alphas": alphas,
                        "diagnosis": diagnosis[:200] + ("..." if len(diagnosis) > 200 else ""),
                        "rationale": rationale[:200] + ("..." if len(rationale) > 200 else "")
                    })

    alignment_score = (aligned_decisions / max(total_decisions, 1)) * 100.0
    
    # Aggregate causal deltas
    causal_summary = {}
    for mode in ["CRUISER", "SHOCK_ABSORBER", "BACKLOG_CLEARER"]:
        deltas = [d for d in causal_deltas if d["action_mode"] == mode]
        if deltas:
            causal_summary[mode] = {
                "count": len(deltas),
                "avg_delta_cost": float(np.mean([d["delta_cost"] for d in deltas])),
                "avg_delta_sl": float(np.mean([d["delta_sl"] for d in deltas]))
            }
            
    return {
        "scenario": scenario_name,
        "total_decisions": total_decisions,
        "alignment_score": alignment_score,
        "mode_distribution": {k: v / max(total_decisions, 1) * 100.0 for k, v in mode_counts.items()},
        "mode_counts": mode_counts,
        "causal_summary": causal_summary,
        "vignettes": vignettes
    }

def print_and_save_analysis(all_results: Dict[str, Any], output_md_path: str):
    """Formats and writes markdown report."""
    lines = []
    lines.append("# LLM Log & Reasoning Fidelity Analysis Report\n")
    lines.append("This report audits the decision quality, intent-to-action alignment, and causal impact of the **Tri-State Meta-LLM Supervisor** across evaluated scenarios.\n")
    
    lines.append("## 1. Intent-to-Action Alignment & State Distribution\n")
    lines.append("| Scenario | Total Decisions | Alignment Score (%) | Cruiser (%) | Shock Absorber (%) | Backlog Clearer (%) |")
    lines.append("|---|---|---|---|---|---|")
    
    for sc, res in all_results.items():
        if not res:
            continue
        tot = res["total_decisions"]
        align = res["alignment_score"]
        dist = res["mode_distribution"]
        lines.append(f"| **{sc.upper()}** | {tot} | **{align:.1f}%** | {dist.get('CRUISER', 0):.1f}% | {dist.get('SHOCK_ABSORBER', 0):.1f}% | {dist.get('BACKLOG_CLEARER', 0):.1f}% |")
        
    lines.append("\n## 2. Window-to-Window Causal Impact of State Transitions\n")
    lines.append("| Scenario | Intervened Mode | Sample Count | Avg $\\Delta$ Window Cost | Avg $\\Delta$ Service Level (%) |")
    lines.append("|---|---|---|---|---|")
    
    for sc, res in all_results.items():
        if not res or "causal_summary" not in res:
            continue
        for mode, c_data in res["causal_summary"].items():
            lines.append(f"| {sc} | `{mode}` | {c_data['count']} | {c_data['avg_delta_cost']:+.2f} | {c_data['avg_delta_sl']:+.1f}% |")
            
    lines.append("\n## 3. Representative Qualitative Vignettes\n")
    for sc, res in all_results.items():
        if not res or "vignettes" not in res:
            continue
        lines.append(f"### Scenario: `{sc}`\n")
        for v in res["vignettes"]:
            lines.append(f"- **Trace:** `{v['trace_id']}` at $t={v['timestep']}$")
            lines.append(f"  - **Selected Mode:** `{v['action_mode']}` with $\\alpha={v['alphas']}$")
            if "diagnosis" in v and v["diagnosis"]:
                lines.append(f"  - **Diagnosis:** *\"{v['diagnosis']}\"*")
            if "rationale" in v and v["rationale"]:
                lines.append(f"  - **Rationale:** *\"{v['rationale']}\"*")
            lines.append("")

    report_content = "\n".join(lines)
    print(report_content)
    
    with open(output_md_path, "w", encoding="utf-8") as f:
        f.write(report_content)
    print(f"\n[INFO] Saved reasoning analysis report to {output_md_path}")

if __name__ == "__main__":
    results_base = os.path.join(PROJECT_ROOT, "experiments", "results_stress_and_regime")
    scenarios = ["stress_shock", "sustained_up", "sustained_down"]
    
    all_analysis = {}
    for sc in scenarios:
        log_dir = os.path.join(results_base, f"llm_logs_{sc}")
        if os.path.exists(log_dir):
            res = analyze_log_directory(log_dir, scenario_name=sc)
            all_analysis[sc] = res
            
    out_md = os.path.join(results_base, "llm_reasoning_fidelity_report.md")
    print_and_save_analysis(all_analysis, out_md)
